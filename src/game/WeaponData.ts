  type: WeaponType;
  name: string;
  category: WeaponCategory;
  damage: number;
  magSize: number; // -1 = infinito (melee)
  cooldownTicks: number;
  projectileSpeed: number;
  accuracyDeg: number;
  pelletCount?: number;
  explosionRadius?: number;
  hasLaserSight?: boolean;
  onFireDuration?: number;
